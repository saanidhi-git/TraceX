        {accounts.length ? accounts.map((account) => <div key={account.account_id} className="risk-detail"><AccountRow account={account} /><div className="contributions">{Object.entries(account.score_breakdown).length ? Object.entries(account.score_breakdown).map(([type, value]) => <span key={type}>{labelize(type)} <b>{value}</b></span>) : <span>No suspicious-pattern contribution identified</span>}<span>ML anomaly rank <b>{account.model_anomaly_score === null ? "n/a" : account.model_anomaly_score}</b></span>{rings.filter((ring) => ring.account_ids.includes(account.account_id)).map((ring) => <span key={ring.ring_id}>Suspected group <b>{ring.ring_id}</b></span>)}</div></div>) : <div className="empty-state">Account risk scores appear after analysis.</div>}
