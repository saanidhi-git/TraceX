import { lazy, Suspense, useCallback, useEffect, useState, type ReactNode } from "react";
import { api } from "./api";
import type { AccountRisk, AnalysisHistory, AnalysisReport, Dataset, GraphData } from "./types";

const GraphView = lazy(() => import("./GraphView").then((module) => ({ default: module.GraphView })));
const navItems = ["Overview", "Datasets", "Transaction graph", "Detection explorer", "Risk analysis", "Reports", "Methodology"];
const money = (value: number) => new Intl.NumberFormat("en-US", { style: "currency", currency: "USD", maximumFractionDigits: 0 }).format(value);
const labelize = (value: string) => value.replace(/_/g, " ");

export default function App() {
  const [page, setPage] = useState("Overview");
  const [datasets, setDatasets] = useState<Dataset[]>([]);
  const [selectedDataset, setSelectedDataset] = useState("");
  const [analysisId, setAnalysisId] = useState("");
  const [report, setReport] = useState<AnalysisReport | null>(null);
  const [history, setHistory] = useState<AnalysisHistory[]>([]);
  const [graph, setGraph] = useState<GraphData | null>(null);
  const [busy, setBusy] = useState(false);
  const [apiOnline, setApiOnline] = useState<boolean | null>(null);
  const [detectorConfig, setDetectorConfig] = useState<Record<string, number>>({
    min_cycle_length: 3, max_cycle_length: 5, max_cycle_window_hours: 72,
    smurf_min_counterparties: 3, smurf_min_total_amount: 1000,
    rapid_pass_through_minutes: 60, min_layered_hops: 3,
    burst_min_transactions: 5, burst_window_minutes: 30,
  });
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");

  const loadDatasets = useCallback(async () => {
    try {
      const list = await api.datasets();
      setDatasets(list);
      setSelectedDataset((current) => current || list[0]?.dataset_id || "");
    } catch (cause) { setError(cause instanceof Error ? cause.message : "Could not load datasets"); }
  }, []);

  const loadHistory = useCallback(async () => {
    try { setHistory((await api.history()).items); }
    catch (cause) { setError(cause instanceof Error ? cause.message : "Could not load analysis history"); }
  }, []);

  useEffect(() => { void loadDatasets(); }, [loadDatasets]);
  useEffect(() => { void loadHistory(); }, [loadHistory]);

  useEffect(() => {
    let active = true;
    const check = async () => {
      try { await api.health(); if (active) setApiOnline(true); }
      catch { if (active) setApiOnline(false); }
    };
    void check();
    const interval = window.setInterval(() => { void check(); }, 15000);
    return () => { active = false; window.clearInterval(interval); };
  }, []);

  useEffect(() => {
    if (!analysisId) return;
    let active = true;
    let timer: number;
    const poll = async () => {
      try {
        const status = await api.status(analysisId);
        if (!active) return;
        if (status.status === "completed") {
          const [nextReport, nextGraph] = await Promise.all([api.report(analysisId), api.graph(analysisId)]);
          if (active) { setReport(nextReport); setGraph(nextGraph); setBusy(false); void loadHistory(); }
        } else if (status.status === "failed") {
          setError(status.error ?? "Analysis failed");
          setBusy(false);
        } else {
          timer = window.setTimeout(() => { void poll(); }, 900);
        }
      } catch (cause) {
        if (active) { setError(cause instanceof Error ? cause.message : "Analysis status unavailable"); setBusy(false); }
      }
    };
    void poll();
    return () => { active = false; window.clearTimeout(timer); };
  }, [analysisId, loadHistory]);

  async function runAnalysis() {
    if (!selectedDataset) return;
    setBusy(true); setError(""); setNotice("Analysis queued. Results are generated by the backend detectors.");
    setReport(null); setGraph(null);
    try {
      const result = await api.startAnalysis(selectedDataset, detectorConfig);
      setAnalysisId(result.analysis_id);
    } catch (cause) {
      setBusy(false); setError(cause instanceof Error ? cause.message : "Could not start analysis");
    }
  }

  async function onUpload(file?: File) {
    if (!file) return;
    setBusy(true); setError(""); setNotice("");
    try {
      const result = await api.upload(file);
      await loadDatasets();
      setSelectedDataset(result.dataset_id);
      if (result.rejected_count > 0) {
        const report = await api.rejections(result.dataset_id);
        const link = document.createElement("a");
        link.href = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: "application/json" }));
        link.download = `graphsentinel-errors-${result.dataset_id}.json`;
        link.click();
        URL.revokeObjectURL(link.href);
      }
      setNotice(`Dataset uploaded with ${result.transaction_count} accepted transaction(s). ${result.rejected_count} invalid row(s) rejected${result.rejected_count ? "; an error report was downloaded." : "."}`);
    } catch (cause) { setError(cause instanceof Error ? cause.message : "Upload failed"); }
    finally { setBusy(false); }
  }

  function downloadReport() {
    if (!report) return;
    const link = document.createElement("a");
    link.href = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: "application/json" }));
    link.download = `graphsentinel-${report.analysis_id}.json`;
    link.click();
    URL.revokeObjectURL(link.href);
  }

  const data = (
    <div className="app-shell">
      <aside className="sidebar">
        <a className="brand" href="#" onClick={(event) => { event.preventDefault(); setPage("Overview"); }}>
          <span className="brand-mark">G</span><span>Graph<span className="brand-light">Sentinel</span><small>FINANCIAL INTELLIGENCE</small></span>
        </a>
        <div className="nav-caption">WORKSPACE</div>
        <nav>{navItems.map((item, index) =>
          <button key={item} className={`nav-item ${page === item ? "active" : ""}`} onClick={() => setPage(item)}>
            <span className="nav-symbol">{["⌂", "▤", "◉", "⚑", "▥", "⇩", "ⓘ"][index]}</span>{item}
            {item === "Detection explorer" && report && <span className="nav-count">{report.summary.patterns_detected}</span>}
          </button>,
        )}</nav>
        <div className="sidebar-bottom">
          <span className="status-dot" /> DEMO ENVIRONMENT
          <p>Outputs are investigative leads, not proof of wrongdoing.</p>
        </div>
      </aside>
      <main className="main-area">
        <header className="topbar">
          <div><span className="eyebrow">INVESTIGATIONS /</span> <strong>{page}</strong></div>
          <div className="top-right"><span className={`api-dot ${apiOnline ? "online" : apiOnline === false ? "offline" : ""}`} /> {apiOnline ? "API online" : apiOnline === false ? "API unavailable" : "Checking API"} <span className="avatar">GS</span></div>
        </header>
        <div className="content">
          {error && <div className="alert error" role="alert">{error}<button onClick={() => setError("")}>×</button></div>}
          {notice && <div className="alert notice">{notice}<button onClick={() => setNotice("")}>×</button></div>}
          {page === "Overview" && <Overview report={report} history={history} datasets={datasets} onRun={runAnalysis} busy={busy} />}
          {page === "Datasets" && <DatasetPage datasets={datasets} selected={selectedDataset} onSelect={setSelectedDataset} onUpload={onUpload} onRun={runAnalysis} busy={busy} />}
          {page === "Transaction graph" && <GraphPage graph={graph} report={report} analysisId={analysisId} onGraphChange={setGraph} />}
          {page === "Detection explorer" && <DetectionPage report={report} onFeedback={async (patternId, feedback) => {
            if (!report) return;
            await api.saveFeedback(report.analysis_id, patternId, feedback);
            setNotice(feedback === "false_positive" ? "False-positive review feedback saved." : "Review status saved.");
          }} />}
          {page === "Risk analysis" && <RiskPage accounts={report?.accounts ?? []} model={report?.model ?? null} rings={report?.rings ?? []} />}
          {page === "Reports" && <ReportsPage report={report} onDownload={downloadReport} />}
          {page === "Methodology" && <MethodologyPage config={detectorConfig} onConfigChange={setDetectorConfig} />}
          <footer>GRAPHSENTINEL <span>·</span> Synthetic data demo <span>·</span> v1.0.0</footer>
        </div>
      </main>
    </div>
  );
  return data;
}

function PageHeading({ kicker, title, description, action }: { kicker: string; title: string; description: string; action?: ReactNode }) {
  return <div className="page-heading"><div><p className="eyebrow">{kicker}</p><h1>{title}</h1><p className="description">{description}</p></div>{action}</div>;
}

